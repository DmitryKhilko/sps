/* ==========================================================================
   tiles.js — делает кликабельной всю плитку на главной странице (index.md)

   Задача. В docs/index.md плитки перехода создаются блоком:
       <div class="grid cards" markdown> ... </div>
   Внутри каждой плитки (элемента списка <li>) стоит одна ссылка на статью:
   заголовок плитки, например
       [**Глоссарий**](glossary.md#article-overview){ data-preview }
   Тема открывает страницу только при клике именно по этой ссылке (по тексту
   заголовка). Этот скрипт добавляет поведение: клик в любом месте плитки
   (по значку, описанию, пустому месту) открывает ту же ссылку.

   Расположение: theme-custom/javascripts/tiles.js
   Папка theme-custom задана в zensical.toml в разделе [project.theme]:
       custom_dir = "theme-custom"
   (Zensical берёт собственные стили и скрипты сайта из этой папки.)

   Подключение. В zensical.toml в разделе [project] стоит строка:
       extra_javascript = ["javascripts/tiles.js"]
   Путь в ней записан относительно папки theme-custom, поэтому без префикса
   theme-custom/. Строка должна находиться ВЫШЕ первого заголовка
   [project.theme]: иначе в TOML она окажется в другой таблице, и Zensical
   её не увидит.

   Парный файл: theme-custom/stylesheets/extra.css (подключается строкой
   extra_css в том же разделе [project]).

   Почему слушатель повешен на весь документ, а не на сами плитки.
   На сайте включена мгновенная навигация (navigation.instant): страницы
   подгружаются без полной перезагрузки, и элементы плиток каждый раз
   создаются заново. Обработчик, привязанный к конкретным плиткам, терялся
   бы после перехода между страницами. Обработчик на document создаётся один
   раз и работает всегда (этот приём называется делегированием событий).

   Внешний вид плитки (курсор-«рука») задаётся в extra.css, раздел 1.
   ========================================================================== */

// Один слушатель на все клики по странице
document.addEventListener("click", function (e) {

  // Ищем плитку, внутри которой произошёл клик: ближайшего родителя <li>
  // внутри блока с классами "grid" и "cards". e.target — элемент, по которому
  // реально кликнул читатель (текст, значок, пустое место плитки и т.п.).
  const card = e.target.closest(".grid.cards li");

  // Клик был вне плитки — ничего не делаем, обычное поведение страницы
  if (!card) return;

  // Если читатель кликнул по самой ссылке, браузер и так её откроет
  // (в том числе с мгновенной навигацией). Повторно запускать её не нужно,
  // иначе переход мог бы сработать дважды.
  if (e.target.closest("a")) return;

  // Находим в плитке ссылку с адресом (a с атрибутом href): это заголовок
  // плитки. Берётся первая найденная: в каждой плитке должна быть одна ссылка.
  // Если добавить в плитку вторую ссылку, скрипт всё равно откроет первую.
  const link = card.querySelector("a[href]");

  // Программно «нажимаем» на эту ссылку. Браузер и тема обрабатывают такой
  // клик так же, как настоящий: открывают страницу и переходят к якорю
  // (например, #article-overview). Окно предпросмотра { data-preview } при
  // этом не показывается: оно появляется только при наведении курсора на
  // сам заголовок-ссылку.
  if (link) link.click();
});
